//! The admin dashboard (js_dashboard_server.js): a separate HTTPS server on
//! dashboard_port with the read-mostly admin UI. The middleware runs in the
//! Express app's order: helmet and cors headers, CORS preflight, bodies,
//! /public static files, the /admin router, `/` -> login, then the 404 page.
//!
//! Differences from the Node.js server: the default error page shows the
//! error without the stack trace, and static files ignore Range requests
//! (always the whole file).

