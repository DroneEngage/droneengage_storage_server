pub struct App {
    pub storage: Arc<Storage>,
    pub admin: admin::AdminRouter,
    m_views: minijinja::Environment<'static>,
    m_root: PathBuf,
}

impl App {
    pub fn render(&self, p_view: &str, p_ctx: minijinja::Value) -> Result<String, String> {
        self.m_views.get_template(p_view).and_then(|t| t.render(p_ctx)).map_err(|e| e.to_string())
    }

    /// <configFile>.local
    pub fn local_config_path(&self) -> PathBuf {
        let mut v = self.storage.cfg().file().as_os_str().to_owned();
        v.push(".local");
        PathBuf::from(v)
    }

    /// writeLocalConfigLimits: server.config.local with `limits` replaced,
    /// other keys kept.
    pub fn write_local_limits(&self, p_limits: &Value) -> Result<(), String> {
        let v_path = self.local_config_path();
        let mut v_existing = if v_path.exists() {
            match std::fs::read_to_string(&v_path).map_err(|e| e.to_string()).and_then(|t| {
                serde_json::from_str::<Value>(&crate::config::strip_json_comments(&t)).map_err(|e| e.to_string())
            }) {
                Ok(v) => v,
                Err(e) => {
                    eprintln!("[dashboard] Could not parse server.config.local: {}", e);
                    Value::Object(Map::new())
                }
            }
        } else {
            Value::Object(Map::new())
        };
        match &mut v_existing {
            Value::Object(m) => {
                m.insert("limits".into(), p_limits.clone());
            }
            Value::Array(_) => {}
            other => return Err(format!("Cannot create property 'limits' on {}", js_interp(Some(other)))),
        }
        let v_text = format!(
            "// Auto-generated by storage server admin dashboard.\n// Merged on top of server.config at startup (shallow merge).\n// Do NOT commit — this file is git-ignored.\n{}\n",
            crate::util::js_stringify_pretty(&v_existing, 4)
        );
        std::fs::write(&v_path, v_text).map_err(|e| e.to_string())
    }
}

/// The 404 page.
pub fn not_found(p_app: &App, p_req: &Request, p_res: &mut Response) {
    p_res.status = 404;
    match p_app.render("pages/404.html", minijinja::context! { title => "404", message => "Not found." }) {
        Ok(h) => p_res.html(p_req, h),
        Err(e) => *p_res = Response::error_page(500, "Error", &e),
    }
}

fn mime(p_path: &std::path::Path) -> &'static str {
    match p_path.extension().and_then(|e| e.to_str()).unwrap_or("").to_ascii_lowercase().as_str() {
        "css" => "text/css; charset=UTF-8",
        "js" | "mjs" => "application/javascript; charset=UTF-8",
        "json" | "map" => "application/json; charset=UTF-8",
        "html" | "htm" => "text/html; charset=UTF-8",
        "txt" => "text/plain; charset=UTF-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "gif" => "image/gif",
        "ico" => "image/x-icon",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "ttf" => "font/ttf",
        _ => "application/octet-stream",
    }
}

/// express.static('public') under /public: None falls through.
fn serve_static(p_app: &App, p_req: &Request, p_rest: &str) -> Option<Response> {
    if p_req.method != "GET" && p_req.method != "HEAD" {
        return None;
    }
    let v_decoded = http::percent_decode(if p_rest.is_empty() { "/" } else { p_rest })?;
    if v_decoded.contains('\0') {
        return None;
    }
    let v_segments: Vec<&str> = v_decoded.split(['/', '\\']).collect();
    if v_segments.iter().any(|s| *s == ".." || (s.starts_with('.') && !s.is_empty())) {
        return None;
    }
    let v_path = p_app.m_root.join("public").join(v_decoded.trim_start_matches('/'));
    let v_meta = std::fs::metadata(&v_path).ok()?;
    let mut r = Response::new();
    if v_meta.is_dir() {
        if v_decoded.ends_with('/') {
            // no index.html
            let v_index = v_path.join("index.html");
            if !v_index.is_file() {
                return None;
            }
            return serve_file(p_req, &v_index, r);
        }
        let v_loc = http::encode_url(&format!(
            "{}/{}",
            p_req.path,
            if p_req.query_raw.is_empty() { String::new() } else { format!("?{}", p_req.query_raw) }
        ));
        let v_body = format!(
            "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n<title>Redirecting</title>\n</head>\n<body>\n<pre>Redirecting to {}</pre>\n</body>\n</html>\n",
            http::escape_html(&v_loc)
        );
        r.status = 301;
        r.set("Content-Type", "text/html; charset=UTF-8");
        r.set("Content-Length", v_body.len().to_string());
        r.set("Content-Security-Policy", "default-src 'none'");
        r.set("X-Content-Type-Options", "nosniff");
        r.set("Location", v_loc);
        r.body = v_body.into_bytes();
        return Some(r);
    }
    r.status = 200;
    serve_file(p_req, &v_path, r)
}

fn serve_file(p_req: &Request, p_path: &std::path::Path, mut r: Response) -> Option<Response> {
    let v_meta = std::fs::metadata(p_path).ok()?;
    let v_mtime = v_meta
        .modified()
        .ok()
        .and_then(|m| m.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0);
    let v_etag = format!("W/\"{:x}-{:x}\"", v_meta.len(), v_mtime);
    r.set("Accept-Ranges", "bytes");
    r.set("Cache-Control", "public, max-age=0");
    r.set("Last-Modified", http::http_date(v_mtime));
    r.set("ETag", v_etag.clone());
    if http::fresh(p_req, Some(&v_etag), Some(v_mtime)) {
        r.status = 304;
        return Some(r);
    }
    r.set("Content-Type", mime(p_path));
    r.set("Content-Length", v_meta.len().to_string());
    r.body = if p_req.method == "HEAD" { Vec::new() } else { std::fs::read(p_path).ok()? };
    Some(r)
}

/// The Express app for one request.
pub fn handle(p_app: &App, p_req: &Request) -> Response {
    // cors(): every OPTIONS is a preflight
    if p_req.method == "OPTIONS" {
        let mut r = Response::new();
        r.status = 204;
        r.set("Access-Control-Allow-Methods", "GET,HEAD,PUT,PATCH,POST,DELETE");
        if let Some(h) = p_req.header("access-control-request-headers") {
            r.set("Vary", "Access-Control-Request-Headers");
            r.set("Access-Control-Allow-Headers", h.to_string());
        }
        r.set("Content-Length", "0");
        return r;
    }
    let v_body = match http::parse_body(p_req) {
        Ok(b) => b,
        Err(e) => {
            eprintln!("{}: {}", e.name, e.message);
            return Response::error_page(e.status, e.name, &e.message);
        }
    };
    let v_path = p_req.path.as_str();
    let v_lower = v_path.to_ascii_lowercase();
    if v_lower == "/public" || v_lower.starts_with("/public/") {
        if let Some(r) = serve_static(p_app, p_req, &v_path[7..]) {
            return r;
        }
    }
    if v_lower == "/admin" || v_lower.starts_with("/admin/") {
        let v_rest = if v_path.len() > 6 { &v_path[6..] } else { "/" };
        if let Some(r) = admin::handle(p_app, p_req, &v_body, v_rest) {
            return r;
        }
    }
    let mut r = Response::new();
    if (p_req.method == "GET" || p_req.method == "HEAD") && v_path == "/" {
        r.redirect(p_req, &admin::admin_path(p_app, "/login"));
        return r;
    }
    not_found(p_app, p_req, &mut r);
    r
}

/// bcryptjs.hashSync(p, 10): a `$2a$10$` hash.
fn bcrypt_hash(p_plain: &str) -> Option<String> {
    bcrypt::hash_with_result(p_plain, 10).ok().map(|h| h.format_for_version(bcrypt::Version::TwoA))
}

/// handleConfig: `$$HASH$$('plaintext')` values (top-level keys) become
/// bcrypt hashes in memory and in the config file.
fn hash_config_values(p_storage: &Storage) {
    let v_raw = p_storage.cfg().raw().clone();
    let Value::Object(m) = v_raw else { return };
    let v_re = regex::Regex::new(r#"\$\$HASH\$\$\(\s*['"]([^'"]+)['"]\s*\)"#).unwrap();
    let mut v_changed = false;
    for (k, v) in m {
        let Value::String(t) = &v else { continue };
        let Some(v_plain) = v_re.captures(t).map(|c| c[1].to_string()) else { continue };
        let Some(v_hash) = bcrypt_hash(&v_plain) else { continue };
        p_storage.update_cfg(|c| c.set(&k, Value::String(v_hash)));
        v_changed = true;
        println!("{}[ConfigHandler] Hashed sensitive config value: {}{}", c::LOG, k, c::RESET);
    }
    if !v_changed {
        return;
    }
    let v_file = p_storage.cfg().file().to_path_buf();
    let v_text = match std::fs::read_to_string(&v_file) {
        Ok(t) => t,
        Err(e) => {
            eprintln!("{}[ConfigHandler] Cannot read config file for persistence: {}{}", c::ERROR, e, c::RESET);
            return;
        }
    };
    let v_file_re = regex::Regex::new(r#"\$\$HASH\$\$\(\s*(?:'([^']+)'|\\?"([^"\\]+)\\?")\s*\)"#).unwrap();
    let mut v_any = false;
    let v_updated = v_file_re.replace_all(&v_text, |caps: &regex::Captures| {
        let v_plain = caps.get(1).or(caps.get(2)).map(|m| m.as_str()).unwrap_or("");
        if v_plain.is_empty() {
            return caps[0].to_string();
        }
        v_any = true;
        bcrypt_hash(v_plain).unwrap_or_else(|| caps[0].to_string())
    });
    if !v_any {
        return;
    }
    match std::fs::write(&v_file, v_updated.as_bytes()) {
        Ok(()) => println!("{}[ConfigHandler] Config file updated — hashed values persisted.{}", c::SUCCESS, c::RESET),
        Err(e) => eprintln!("{}[ConfigHandler] Failed to write config file: {}{}", c::ERROR, e, c::RESET),
    }
}

/// The dashboard listener; `run` reports it and serves.
pub struct Dashboard {
    m_app: Arc<App>,
    m_listener: Result<TcpListener, String>,
    m_acceptor: Option<tokio_rustls::TlsAcceptor>,
    m_ip: String,
    m_port: String,
}

/// start(): checks the config, builds the app, binds dashboard_port.
pub async fn start(p_storage: &Arc<Storage>) -> Result<Option<Dashboard>, String> {
    let v_cfg = p_storage.cfg().clone();
    let v_ip = match v_cfg.get("dashboard_listening_ip").filter(|v| js_truthy(Some(v))) {
        Some(v) => js_interp(Some(v)),
        None => {
            println!(
                "{}FATAL ERROR:{} dashboard_listening_ip {} is not specified in config file.",
                c::B_ERROR,
                c::FG_YELLOW,
                c::RESET
            );
            std::process::exit(0);
        }
    };
    let v_port = match std::env::var("de_storage_dashboard_port") {
        Ok(p) if !p.is_empty() => p,
        _ => match v_cfg.get("dashboard_port").filter(|v| js_truthy(Some(v))) {
            Some(v) => js_interp(Some(v)),
            None => "9001".into(),
        },
    };

    // js_admin_session.js, loaded with the router
    let v_secret = v_cfg.get("session_secret").filter(|v| js_truthy(Some(v))).map(|v| js_interp(Some(v)));
    if v_secret.is_none() || v_secret.as_deref() == Some("change-this-secret-in-production") {
        println!(
            "{}[WARNING]{} session_secret {} is missing or still set to the default value in the config file. Set a unique, high-entropy secret before using in production.",
            c::B_ERROR,
            c::B_FG_YELLOW,
            c::RESET
        );
    }
    hash_config_values(p_storage);

    let v_ssl = js_truthy(v_cfg.get("enable_SSL"));
    let mut v_acceptor = None;
    let v_files = (
        v_cfg.get("ssl_cert_file").filter(|v| js_truthy(Some(v))),
        v_cfg.get("ssl_key_file").filter(|v| js_truthy(Some(v))),
    );
    if let (true, (Some(v_cert), Some(v_key))) = (v_ssl, v_files) {
        let v_cert = v_cfg.resolve(&crate::util::js_to_string(v_cert));
        let v_key = v_cfg.resolve(&crate::util::js_to_string(v_key));
        if v_cert.exists() && v_key.exists() {
            v_acceptor = Some(crate::net::tls_acceptor(&v_key, &v_cert)?);
            p_storage.log.info("SSL/TLS enabled for dashboard server");
        } else {
            p_storage.log.warn("SSL enabled but cert/key not found, dashboard falling back to HTTP");
        }
    }

    let v_app = Arc::new(App {
        storage: p_storage.clone(),
        admin: admin::AdminRouter::new(v_secret, v_ssl),
        m_views: views::environment(&v_cfg.base_dir().join("views")),
        m_root: v_cfg.base_dir().to_path_buf(),
    });
    {
        let v_app = v_app.clone();
        tokio::spawn(async move {
            loop {
                tokio::time::sleep(Duration::from_secs(300)).await;
                v_app.admin.lockout.sweep();
            }
        });
    }
    let v_listener = crate::ws_server::bind_listener(&v_ip, &v_port).await;
    Ok(Some(Dashboard { m_app: v_app, m_listener: v_listener, m_acceptor: v_acceptor, m_ip: v_ip, m_port: v_port }))
}

async fn service(
    p_app: Arc<App>,
    p_req: hyper::Request<Incoming>,
    p_remote: SocketAddr,
    p_secure: bool,
) -> Result<hyper::Response<Full<Bytes>>, std::convert::Infallible> {
    let (v_parts, v_body) = p_req.into_parts();
    let v_bytes = match v_body.collect().await {
        Ok(b) => b.to_bytes().to_vec(),
        Err(_) => Vec::new(),
    };
    let v_target = v_parts.uri.path_and_query().map(|p| p.as_str()).unwrap_or("/");
    let (v_path, v_query) = v_target.split_once('?').unwrap_or((v_target, ""));
    let v_req = Request {
        method: v_parts.method.as_str().to_string(),
        path: v_path.to_string(),
        query_raw: v_query.to_string(),
        headers: v_parts
            .headers
            .iter()
            .map(|(k, v)| (k.as_str().to_string(), String::from_utf8_lossy(v.as_bytes()).into_owned()))
            .collect(),
        body: v_bytes,
        ip: p_remote.ip().to_string(),
        secure: p_secure,
    };
    let v_res = handle(&p_app, &v_req);
    let mut v_builder = hyper::Response::builder().status(v_res.status);
    for (k, v) in &v_res.headers {
        v_builder = v_builder.header(k.as_str(), v.as_str());
    }
    let v_body = if v_req.method == "HEAD" { Vec::new() } else { v_res.body };
    Ok(v_builder.body(Full::new(Bytes::from(v_body))).unwrap_or_else(|_| hyper::Response::new(Full::new(Bytes::new()))))
}

impl Dashboard {
    pub fn run(self) -> Option<SocketAddr> {
        let v_listener = match self.m_listener {
            Ok(l) => l,
            Err(e) => {
                // an 'error' event with no listener: Node.js would crash here
                eprintln!("Error: {}", e);
                std::process::exit(1);
            }
        };
        let v_addr = v_listener.local_addr().ok();
        println!("{}[OK] Dashboard Server Started{}", c::SUCCESS, c::RESET);
        let v_guid = self
            .m_app
            .storage
            .cfg()
            .get("dashboard_url_guid")
            .filter(|g| js_truthy(Some(g)))
            .map(|g| js_interp(Some(g)));
        let v_login = match &v_guid {
            Some(g) => format!("/admin/{}/login", g),
            None => "/admin/login".into(),
        };
        let v_proto = if js_truthy(self.m_app.storage.cfg().get("enable_SSL")) { "https" } else { "http" };
        println!(
            "{}Dashboard: {}{}://{}:{}{}{}{}",
            c::LOG,
            c::B_SUCCESS,
            v_proto,
            self.m_ip,
            self.m_port,
            v_login,
            c::RESET,
            if v_guid.is_some() { " (GUID mode)" } else { "" }
        );
        let (v_app, v_acceptor) = (self.m_app, self.m_acceptor);
        tokio::spawn(async move {
            loop {
                let Ok((v_tcp, v_remote)) = v_listener.accept().await else {
                    tokio::time::sleep(Duration::from_millis(50)).await;
                    continue;
                };
                let (v_app, v_acceptor) = (v_app.clone(), v_acceptor.clone());
                tokio::spawn(async move {
                    let v_builder = {
                        let mut b = hyper::server::conn::http1::Builder::new();
                        b.title_case_headers(true);
                        b
                    };
                    match v_acceptor {
                        Some(a) => {
                            let Ok(v_tls) = a.accept(v_tcp).await else { return };
                            let v_svc = hyper::service::service_fn(move |r| service(v_app.clone(), r, v_remote, true));
                            let _ = v_builder.serve_connection(TokioIo::new(v_tls), v_svc).await;
                        }
                        None => {
                            let v_svc = hyper::service::service_fn(move |r| service(v_app.clone(), r, v_remote, false));
                            let _ = v_builder.serve_connection(TokioIo::new(v_tcp), v_svc).await;
                        }
                    }
                });
            }
        });
        v_addr
    }
}
